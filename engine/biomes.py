# Смена локации каждые ~15 волн, по спирали вглубь.
BIOME_WAVE_PERIOD = 15
# Сколько полных циклов биомов до «капсулы» глубины (не влияет на акты).
MAX_CYCLE = 4


def biome_for_wave(wave: int) -> Biome:
    """Биом для текущей волны (детерминированно, независимо от боевого акта)."""
    if type(wave) is not int or wave < 1:
        raise ValueError("Номер волны должен быть целым >= 1")
    step = (wave - 1) // BIOME_WAVE_PERIOD
    cycle = min(step // len(BIOME_ORDER), MAX_CYCLE - 1)
    index = (step + cycle) % len(BIOME_ORDER)
    return BIOME_ORDER[index]


def act_banner_for_biome(biome: Biome) -> str:
    """Готический баннер смены локации: «АКТ IV · ЦИТАДЕЛЬ БЕЗДНЫ»."""
    roman = ("I", "II", "III", "IV")[max(0, biome.act_number - 1) % 4]
    return f"АКТ {roman} · {biome.name.upper()}"
