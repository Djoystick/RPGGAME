from __future__ import annotations

from dataclasses import dataclass


# =========================================================================
#  Живой мир Бездны (v1.4.0)
#  Локации/биомы — это слой ПРЕЗЕНТАЦИИ, независимый от боевого «акта»
#  (который закреплён тестами). Арена отображает биом по номеру волны.
# =========================================================================


@dataclass(frozen=True)
class Biome:
    biome_id: str
    name: str
    subtitle: str
    # Три слоя параллакса (дальний фон / средние объекты / пол арены).
    far: tuple[int, int, int]
    mid: tuple[int, int, int]
    floor: tuple[int, int, int]
    # Палитра атмосферы.
    light: str
    accent: str
    # Тип погоды: частицы пепла, снега, спор, дождя, светлячков или дыма.
    weather: str
    # Актовый номер для баннера («АКТ III»).
    act_number: int
    # Параллакс-смещение дальнего слоя.
    parallax: float = 0.35


